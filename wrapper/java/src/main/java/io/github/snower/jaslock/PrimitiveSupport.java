package io.github.snower.jaslock;

import io.github.snower.jaslock.callback.CallbackCommandResult;
import io.github.snower.jaslock.commands.Command;
import io.github.snower.jaslock.commands.CommandResult;
import io.github.snower.jaslock.commands.ICommand;
import io.github.snower.jaslock.commands.LockCommand;
import io.github.snower.jaslock.commands.LockCommandResult;
import io.github.snower.jaslock.datas.LockData;
import io.github.snower.jaslock.exceptions.ClientClosedException;
import io.github.snower.jaslock.exceptions.ClientCommandTimeoutException;
import io.github.snower.jaslock.exceptions.ClientUnconnectException;
import io.github.snower.jaslock.exceptions.EventWaitTimeoutException;
import io.github.snower.jaslock.exceptions.LockDataException;
import io.github.snower.jaslock.exceptions.LockException;
import io.github.snower.jaslock.exceptions.LockLockedException;
import io.github.snower.jaslock.exceptions.LockNotOwnException;
import io.github.snower.jaslock.exceptions.LockTimeoutException;
import io.github.snower.jaslock.exceptions.LockUnlockedException;
import io.github.snower.jaslock.exceptions.SlockException;

import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Arrays;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.function.Consumer;

/**
 * Package-private adapter between the Java compatibility facade and
 * {@link NativeBridge}.
 *
 * <p>This class only converts arguments, completion results and structured
 * errors. Every primitive operation is submitted to Rust; no lock, event or
 * connection algorithm is implemented here.
 */
final class PrimitiveSupport {

    /**
     * Completions that have been submitted but are not ready yet. A single
     * daemon pump waits on the native completion generation, scans only when
     * that generation changes (or after an explicit registration signal), and
     * hands ready results to the configured callback pool. The callback pool is
     * never occupied by a blocked native wait.
     */
    private static final ConcurrentLinkedQueue<PendingCompletion> PENDING_COMPLETIONS =
            new ConcurrentLinkedQueue<PendingCompletion>();
    private static final AtomicBoolean COMPLETION_PUMP_STARTED = new AtomicBoolean(false);

    /**
     * Negative means "wait until the native epoch changes". This is one
     * {@code Condvar} wait, not a periodic sleep, so it is not subject to
     * Windows timer-tick throttling. Waiting indefinitely is safe: every native
     * completion bumps the epoch after its result becomes visible, and every
     * registration signals the pump after its token is queued, so no ready
     * token can be stranded.
     */
    private static final long COMPLETION_WAIT_MILLIS = -1L;

    private PrimitiveSupport() {
    }

    /**
     * Creates a native lock handle and applies the caller's initial count and
     * priority count, which are not part of the factory signature.
     */
    static long createLock(SlockDatabase database, byte[] key, byte[] explicitLockId,
                           int timeout, int expried, short count, byte rCount) {
        long handle = NativeBridge.lockCreate(database.nativeHandle(), key, timeout, expried,
                normalizeLockId(explicitLockId));
        try {
            if (count != 0) {
                updateLockCount(handle, NativeBridge.OP_LOCK_SET_COUNT, count & 0xffff);
            }
            if (rCount != 0) {
                updateLockCount(handle, NativeBridge.OP_LOCK_SET_R_COUNT, rCount & 0xff);
            }
            return handle;
        } catch (RuntimeException e) {
            NativeBridge.release(handle);
            throw e;
        }
    }

    static long createEvent(SlockDatabase database, byte[] key, int timeout, int expried,
                            boolean defaultSeted) {
        return NativeBridge.eventCreate(database.nativeHandle(), key, timeout, expried,
                defaultSeted);
    }

    /**
     * Normalizes an explicit lock id using the same Jaslock rules: {@code null}
     * stays generated by Rust, values longer than 16 bytes are MD5-hashed and
     * shorter values are left-padded. The returned value is never used as a
     * primitive algorithm, only as the fixed-width id sent with the factory.
     */
    static byte[] normalizeLockId(byte[] lockId) {
        if (lockId == null) {
            return null;
        }
        if (lockId.length == 16) {
            return lockId;
        }
        if (lockId.length > 16) {
            try {
                MessageDigest digest = MessageDigest.getInstance("MD5");
                return digest.digest(lockId);
            } catch (NoSuchAlgorithmException e) {
                return Arrays.copyOfRange(lockId, 0, 16);
            }
        }
        byte[] normalized = new byte[16];
        System.arraycopy(lockId, 0, normalized, 16 - lockId.length, lockId.length);
        return normalized;
    }

    /** Builds the command descriptor carried by callback results and exceptions. */
    static LockCommand lockCommand(byte commandType, byte flag, byte dbId, byte[] lockKey,
                                   byte[] lockId, int timeout, int expried, short count,
                                   byte rCount, LockData lockData) {
        byte actualFlag = flag;
        if (lockData != null) {
            actualFlag |= commandType == ICommand.COMMAND_TYPE_UNLOCK
                    ? ICommand.UNLOCK_FLAG_CONTAINS_DATA
                    : ICommand.LOCK_FLAG_CONTAINS_DATA;
        }
        return new LockCommand(commandType, actualFlag, dbId, lockKey, lockId, timeout, expried,
                count, rCount, lockData);
    }

    static NativeBridge.Result submitAndWait(SlockDatabase database, long handle, int op,
                                             int arg0, LockData data) throws SlockException {
        try {
            return NativeBridge.submitAndWait(handle, op, arg0, dumpData(data));
        } catch (IllegalStateException | IllegalArgumentException e) {
            throw submitFailure(e);
        }
    }

    /**
     * Submits an operation and runs the completion consumer on the database's
     * Java callback dispatcher after Rust completes it. The completion is
     * released on every path.
     *
     * <p>The callback pool is not used to wait for Rust. The completion is
     * queued and a shared readiness pump wakes on the native completion epoch,
     * scans the queue, and dispatches only already-ready results, so pending
     * acquires/wait operations cannot starve release or other callbacks.
     */
    static void submitAsync(SlockDatabase database, long handle, int op, int arg0, LockData data,
                            Consumer<NativeBridge.Result> completion) throws SlockException {
        database.requireAsyncCallback();
        NativeBridge.Completion token;
        try {
            token = NativeBridge.submit(handle, op, arg0, dumpData(data));
        } catch (IllegalStateException | IllegalArgumentException e) {
            throw submitFailure(e);
        }

        PendingCompletion pending = new PendingCompletion(database, token, completion);
        boolean immediate;
        try {
            immediate = token.isDone();
        } catch (RuntimeException e) {
            immediate = false;
        }
        if (immediate) {
            // Already complete: deliver without a queue round trip. A dispatch
            // failure still delivers inline so the accepted result is not lost.
            pending.dispatchWhenReady();
            return;
        }

        PENDING_COMPLETIONS.add(pending);
        try {
            ensureCompletionPump();
        } catch (RuntimeException e) {
            // The pump could not start; deliver this accepted completion through
            // the callback dispatcher (or inline) instead of leaving it queued.
            if (PENDING_COMPLETIONS.remove(pending)) {
                pending.dispatchWhenReady();
            }
            return;
        }
        try {
            // Queue-then-signal ordering: a pump that already scanned the queue
            // is woken by the changed epoch, and a registration that lands after
            // the signal is still visible to the next scan.
            NativeBridge.signalCompletionPump();
        } catch (RuntimeException ignored) {
            // The token's own completion bumps the epoch, so a lost explicit
            // signal only delays the scan and never strands the completion.
        }
    }

    private static void ensureCompletionPump() {
        if (!COMPLETION_PUMP_STARTED.compareAndSet(false, true)) {
            return;
        }
        Thread pump = new Thread(PrimitiveSupport::runCompletionPump,
                "jaslock-native-completion");
        pump.setDaemon(true);
        try {
            pump.start();
        } catch (RuntimeException e) {
            COMPLETION_PUMP_STARTED.set(false);
            throw e;
        }
    }

    private static void runCompletionPump() {
        while (true) {
            // Read the epoch before scanning so a completion that lands during
            // the scan either shows up as ready or changes the epoch and
            // releases the wait below immediately.
            long observed;
            try {
                observed = NativeBridge.completionEpoch();
            } catch (RuntimeException e) {
                observed = 0L;
            }

            boolean progressed;
            try {
                progressed = dispatchReady();
            } catch (RuntimeException e) {
                progressed = false;
            }
            if (progressed) {
                // Drain a burst without an extra wait.
                continue;
            }

            try {
                NativeBridge.awaitCompletionChange(observed, COMPLETION_WAIT_MILLIS);
            } catch (RuntimeException e) {
                // Keep the pump alive. A bounded wait avoids a hot spin if the
                // native signal is temporarily unavailable.
                try {
                    NativeBridge.awaitCompletionChange(observed, 1000L);
                } catch (RuntimeException ignored) {
                    Thread.yield();
                }
            }
        }
    }

    private static boolean dispatchReady() {
        boolean progressed = false;
        for (PendingCompletion pending : PENDING_COMPLETIONS) {
            boolean ready;
            try {
                ready = pending.token.isDone();
            } catch (RuntimeException e) {
                if (PENDING_COMPLETIONS.remove(pending)) {
                    pending.discard();
                }
                progressed = true;
                continue;
            }
            if (!ready) {
                continue;
            }
            if (PENDING_COMPLETIONS.remove(pending)) {
                pending.dispatchWhenReady();
                progressed = true;
            }
        }
        return progressed;
    }

    private static final class PendingCompletion {
        private final SlockDatabase database;
        private final NativeBridge.Completion token;
        private final Consumer<NativeBridge.Result> completion;

        private PendingCompletion(SlockDatabase database, NativeBridge.Completion token,
                                  Consumer<NativeBridge.Result> completion) {
            this.database = database;
            this.token = token;
            this.completion = completion;
        }

        private void dispatch() throws SlockException {
            database.dispatch(() -> {
                try {
                    completion.accept(token.await());
                } finally {
                    token.close();
                }
            });
        }

        private void dispatchWhenReady() {
            try {
                dispatch();
            } catch (SlockException | RuntimeException e) {
                deliverInline();
            }
        }

        /**
         * Fallback when the configured callback executor is gone (client close or
         * callback-pool shutdown). The accepted completion is still delivered
         * exactly once on the pump thread rather than being dropped.
         */
        private void deliverInline() {
            try {
                completion.accept(token.await());
            } catch (RuntimeException ignored) {
                // A user callback must not terminate the completion pump.
            } finally {
                token.close();
            }
        }

        private void discard() {
            token.close();
        }
    }

    static byte[] dumpData(LockData data) throws SlockException {
        return data == null ? null : data.dumpData();
    }

    static void throwIfError(NativeBridge.Result result, Command command) throws SlockException {
        if (!result.isOk()) {
            throw toException(result, command);
        }
    }

    static CommandResult commandResult(NativeBridge.Result result) {
        if (result.lock != null) {
            return toLockCommandResult(result.lock);
        }
        if (result.serverResult >= 0) {
            return new CommandResult((byte) result.serverResult);
        }
        return null;
    }

    static CallbackCommandResult callbackResult(Command command, NativeBridge.Result result) {
        return new CallbackCommandResult(command, commandResult(result),
                result.isOk() ? null : toException(result, command));
    }

    /**
     * Rebuilds the public {@link LockCommandResult} from the native result frame
     * through the existing compatibility parser.
     */
    static LockCommandResult toLockCommandResult(NativeBridge.LockResult lockResult) {
        byte[] header = new byte[64];
        header[0] = ICommand.MAGIC;
        header[1] = ICommand.VERSION;
        header[2] = (byte) lockResult.commandType;
        copy(lockResult.requestId, header, 3);
        header[19] = (byte) lockResult.result;
        header[20] = (byte) lockResult.flag;
        header[21] = (byte) lockResult.dbId;
        copy(lockResult.lockId, header, 22);
        copy(lockResult.lockKey, header, 38);
        header[54] = (byte) (lockResult.lCount & 0xff);
        header[55] = (byte) ((lockResult.lCount >> 8) & 0xff);
        header[56] = (byte) (lockResult.count & 0xff);
        header[57] = (byte) ((lockResult.count >> 8) & 0xff);
        header[58] = (byte) lockResult.lrCount;
        header[59] = (byte) lockResult.rCount;

        LockCommandResult result = new LockCommandResult();
        result.parseCommand(header);
        if (lockResult.data != null) {
            result.loadCommandData(lockResult.data);
        }
        return result;
    }

    static SlockException toException(NativeBridge.Result result, Command command) {
        CommandResult commandResult = commandResult(result);
        String message = result.message == null || result.message.isEmpty()
                ? "native operation failed"
                : result.message;
        switch (result.errorKind) {
            case NativeBridge.ERROR_CLIENT_CLOSED:
                return new ClientClosedException(message);
            case NativeBridge.ERROR_NOT_CONNECTED:
            case NativeBridge.ERROR_CLIENT_DISCONNECTED:
            case NativeBridge.ERROR_IO:
                return new ClientUnconnectException(message);
            case NativeBridge.ERROR_COMMAND_TIMEOUT:
                return new ClientCommandTimeoutException(message);
            case NativeBridge.ERROR_LOCK_LOCKED:
                return new LockLockedException(command, commandResult);
            case NativeBridge.ERROR_LOCK_UNLOCKED:
                return new LockUnlockedException(command, commandResult);
            case NativeBridge.ERROR_LOCK_NOT_OWN:
                return new LockNotOwnException(command, commandResult);
            case NativeBridge.ERROR_LOCK_TIMEOUT:
                return new LockTimeoutException(command, commandResult);
            case NativeBridge.ERROR_LOCK_EXPIRED:
            case NativeBridge.ERROR_STATE:
            case NativeBridge.ERROR_SERVER:
                return new LockException(command, commandResult);
            case NativeBridge.ERROR_LOCK_DATA:
                return new LockDataException(message);
            case NativeBridge.ERROR_EVENT_WAIT_TIMEOUT:
                return new EventWaitTimeoutException();
            default:
                return new SlockException(message);
        }
    }

    /** Pushes a count change to the native primitive; used by {@link Lock}. */
    static void updateLockCount(long handle, int op, int value) {
        NativeBridge.Result result = NativeBridge.submitAndWait(handle, op, value, null);
        if (!result.isOk()) {
            throw new IllegalStateException(result.message == null
                    ? "failed to update native lock count"
                    : result.message);
        }
    }

    private static SlockException submitFailure(RuntimeException failure) {
        String message = failure.getMessage();
        if (message == null || message.isEmpty()) {
            message = failure.toString();
        }
        if (failure instanceof IllegalArgumentException && message.contains("lock data")) {
            return new LockDataException(message);
        }
        if (message.toLowerCase().contains("closed")) {
            return new ClientClosedException(message);
        }
        return new SlockException(message);
    }

    private static void copy(byte[] source, byte[] target, int offset) {
        if (source != null) {
            System.arraycopy(source, 0, target, offset, Math.min(source.length, 16));
        }
    }
}
